/*
 * Writes the user-defaults seed function from content/defaults.ts, so SQL and TS can't drift.
 * Run: npx tsx scripts/gen-seed-sql.ts > supabase/migrations/<ts>_seed_defaults.sql
 * tests/unit/seed-sql.test.ts fails if the committed migration differs from this output.
 */
import { DEFAULT_PLOT_SLOTS, DEFAULT_SETTINGS, DEFAULT_TEMPLATES } from "../content/defaults";

export function seedSql(): string {
  const lit = (v: unknown) => `$json$${JSON.stringify(v)}$json$::jsonb`;
  const s = DEFAULT_SETTINGS;
  const templates = DEFAULT_TEMPLATES.map(
    (t) =>
      `    (uid, '${t.key}', '{${t.weekdays.join(",")}}', ${t.auto_apply}, '${t.target_wake}', ${lit(t.options)}, ${lit(t.blocks)}, ${lit(t.fixed_events)}, ${t.sort})`,
  ).join(",\n");
  const plots = DEFAULT_PLOT_SLOTS.map((slot) => `    (uid, '${slot}')`).join(",\n");
  return `-- GENERATED by scripts/gen-seed-sql.ts from content/defaults.ts — do not edit by hand.
-- Seeds Minnie's defaults (SPEC §2, §5, §6) for every new user on first sign-in.

create or replace function public.seed_user_defaults(uid uuid)
returns void
language plpgsql
security definer
set search_path = ''
as $fn$
begin
  insert into public.profiles (user_id) values (uid) on conflict do nothing;

  insert into public.settings (user_id, blocks, gym_close_time, weekly_exercise_goal, kaizen, wake_window_min, tags)
  values (uid, ${lit(s.blocks)}, '${s.gym_close_time}', ${s.weekly_exercise_goal}, ${lit(s.kaizen)}, ${s.wake_window_min}, ${lit(s.tags)})
  on conflict do nothing;

  insert into public.templates (user_id, key, weekdays, auto_apply, target_wake, options, blocks, fixed_events, sort)
  values
${templates}
  on conflict (user_id, key) do nothing;

  insert into public.game_state (user_id) values (uid) on conflict do nothing;

  insert into public.plots (user_id, slot)
  values
${plots}
  on conflict (user_id, slot) do nothing;
end $fn$;

revoke all on function public.seed_user_defaults(uuid) from public, anon, authenticated;

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $fn$
begin
  perform public.seed_user_defaults(new.id);
  return new;
end $fn$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- Existing users (created before this migration) get their defaults too.
select public.seed_user_defaults(id) from auth.users;
`;
}

if (process.argv[1]?.endsWith("gen-seed-sql.ts")) process.stdout.write(seedSql());
